"""READMEs and figure for results/multibrand_fuel_tv (1.2.0) and _trend (1.2.1) from saved CSVs.

python -m scripts.multibrand_fuel_tv_report [--check]
"""
import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
V0 = ROOT / "results/multibrand_fuel_tv"
V1 = ROOT / "results/multibrand_fuel_tv_trend"
INK, MUTED, GRID, SURFACE, BLUE, ORANGE, BAND = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb", "#2a78d6", "#eb6834", "#b7d3f6"
EQ = {"log_market": "BEV market", "alr_Tesla": "Tesla/Rest"}


def rows(folder, name):
    with (folder / name).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def ci(m, lo, hi):
    return f"{float(m):+.2f} [{float(lo):+.2f}; {float(hi):+.2f}]"


def coef_table(folder, a):
    c = rows(folder, "coefficients.csv")
    a("| Variant | Equation | Term | Median [95 %] |")
    a("|---|---|---|---|")
    for r in c:
        if r["equation"] in EQ:
            mark = " **†**" if r["excludes_zero"] == "True" else ""
            a(f"| {r['variant']} | {EQ[r['equation']]} | `{r['term']}` | {ci(r['median'], r['lower95'], r['upper95'])}{mark} |")
    a("")


def path_table(folder, variant, a):
    p = [r for r in rows(folder, "coefficient_path.csv") if r["variant"] == variant]
    months = list(dict.fromkeys(r["month"] for r in p))
    a("| Equation | " + " | ".join(months) + " |")
    a("|---|" + "---|" * len(months))
    for eq in EQ:
        a(f"| {EQ[eq]} | " + " | ".join(ci(r["coefficient_median"], r["lower95"], r["upper95"])
                                         for r in p if r["equation"] == eq) + " |")
    a("")


def ml_table(folder, a):
    ml = rows(folder, "marginal_likelihood.csv")
    base = float(ml[0]["log_marginal_likelihood"])
    a("| Variant | log marginal likelihood | difference to constant base |")
    a("|---|---|---|")
    for r in ml:
        v = float(r["log_marginal_likelihood"])
        a(f"| {r['variant']} | {v:.2f} | {v - base:+.2f} |")
    a("")


def rmse_table(folder, specs, a):
    met = {(r["spec"], r["outcome"], r["period"], r["horizon"]): r for r in rows(folder, "metrics.csv")}
    for outcome in ("Tesla", "BEV_market"):
        a(f"**{outcome.replace('_', ' ')}** (RMSE, registrations per month)\n")
        a("| Model | 2025 h=1 | 2025 h=3 | 2026 h=1 | 2026 h=3 | Oct 2026 h=1 | Oct 2026 h=3 |")
        a("|---|---|---|---|---|---|---|")
        for s in specs:
            vals = []
            for p, h in (("2025", "1"), ("2025", "3"), ("2026", "1"), ("2026", "3"), ("2026-10", "1"), ("2026-10", "3")):
                r = met.get((s, outcome, p, h))
                vals.append(f"{float(r['rmse']):,.0f}" if r else "–")
            a(f"| {s} | " + " | ".join(vals) + " |")
        a("")


def hyp_table(folder, a):
    a("| Variant | Hypothesis | Slope / step b1 [95 %] | Verdict |")
    a("|---|---|---|---|")
    for r in rows(folder, "hypotheses.csv"):
        a(f"| {r['variant']} | {r['hypothesis']} | {ci(r['median'], r['lower95'], r['upper95'])} | {r['verdict']} |")
    a("")


def build_v0():
    man = json.loads((V0 / "manifest.json").read_text())
    L = []
    a = L.append
    a("# Time-varying fuel coefficient at lag 1 — amendment 1.2.0 (as run, **affected by a specification flaw**)\n")
    a("> **Do not use the `tv_linear` and `tv_linear_loose` slopes below.** The interaction "
      "`τ_t · log_fuel_{t-1}` was added without the main effect `τ_t`; since log fuel stays far from zero "
      "the slope also absorbs a linear time trend. Corrected in "
      "[amendment 1.2.1](../multibrand_fuel_tv_trend/README.md). The `tv_step_2024` variant is not "
      "affected (its main effect is spanned by the intercept and the grant indicators). Results are kept "
      "unchanged for transparency.\n")
    a("Generated by `python -m scripts.multibrand_fuel_tv_report` from the CSVs in this folder. "
      "[Amendment](../../docs/MULTIBRAND_FUEL_TV_PROTOCOL.md) SHA-256 `" + man["protocol_sha256"][:16]
      + f"…`, {man['draws']:,} draws, outcome months {man['outcome_months']}. b(t) = b0 + b1 · g(t); "
      "g = years from mid-sample (linear) or 1 from 2024-01 (step). † = 95 % interval excludes zero.\n")
    a("## Verdicts (frozen rule)\n")
    hyp_table(V0, a)
    a("## Coefficients\n")
    coef_table(V0, a)
    a("## Implied coefficient b(t) — step variant\n")
    path_table(V0, "tv_step_2024", a)
    a("## Log marginal likelihood\n")
    ml_table(V0, a)
    a("## Forecasts\n")
    rmse_table(V0, ("tv_linear", "tv_linear_loose", "tv_step_2024", "constant_L1", "M2"), a)
    return "\n".join(L) + "\n"


def build_v1():
    man = json.loads((V1 / "manifest.json").read_text())
    L = []
    a = L.append
    a("# Time-varying fuel coefficient at lag 1 — corrected amendment 1.2.1\n")
    a("Generated by `python -m scripts.multibrand_fuel_tv_report` from the CSVs in this folder. "
      "[Amendment](../../docs/MULTIBRAND_FUEL_TV_TREND_PROTOCOL.md) frozen before fitting (SHA-256 `"
      + man["protocol_sha256"][:16] + f"…`), {man['draws']:,} draws, outcome months {man['outcome_months']}. "
      "Every equation gets a linear trend τ (years from mid-sample) **and** the interaction τ · log_fuel_{t-1}, "
      "so the fuel coefficient at lag 1 is b(t) = b0 + b1 · τ_t. "
      "The flawed first attempt is documented in [1.2.0](../multibrand_fuel_tv/README.md). "
      "Associations, not causal effects; † = 95 % interval excludes zero.\n")
    a("## 1. Verdicts (frozen rule: b1 interval above zero = rising)\n")
    hyp_table(V1, a)
    a("## 2. Implied fuel coefficient over time (primary `tv_linear_trend`)\n")
    a("Elasticity of the BEV market (log points per log point of the fuel price, one month later) and of the "
      "Tesla/Rest log ratio:\n")
    path_table(V1, "tv_linear_trend", a)
    a("![Fuel coefficient over time](fuel_coefficient_path.png)\n")
    a("## 3. All coefficients\n")
    coef_table(V1, a)
    a("## 4. Log marginal likelihood\n")
    ml_table(V1, a)
    a("Adding regressors with a deliberately wide prior (the trend term) is penalised by the marginal "
      "likelihood almost regardless of fit (Bartlett/Lindley effect), so these differences mainly reflect "
      "prior width; the forecast comparison below is the more informative check.\n")
    a("## 5. Forecasts\n")
    rmse_table(V1, ("tv_linear_trend", "tv_linear_trend_loose", "trend_only", "constant_L1", "M2"), a)
    a("## Files\n")
    a("`coefficients.csv`, `coefficient_path.csv`, `marginal_likelihood.csv`, `predictions.csv`, `metrics.csv`, "
      "`hypotheses.csv`, `manifest.json`. Reproduce:\n")
    a("```sh\npython -m multibrand.fuel_tv\npython -m multibrand.fuel_tv_trend\npython -m scripts.multibrand_fuel_tv_report\n```")
    return "\n".join(L) + "\n"


def figure():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    good = [r for r in rows(V1, "coefficient_path.csv") if r["variant"] == "tv_linear_trend"]
    bad = [r for r in rows(V0, "coefficient_path.csv") if r["variant"] == "tv_linear"]
    fig, axes = plt.subplots(1, 2, figsize=(10, 4.2), facecolor=SURFACE)
    for ax, eq in zip(axes, EQ):
        g = [r for r in good if r["equation"] == eq]
        b = [r for r in bad if r["equation"] == eq]
        x = range(len(g))
        ax.set_facecolor(SURFACE)
        ax.fill_between(x, [float(r["lower95"]) for r in g], [float(r["upper95"]) for r in g], color=BAND,
                        linewidth=0, label="1.2.1 corrected, 95 %")
        ax.plot(x, [float(r["coefficient_median"]) for r in g], color=BLUE, linewidth=2, marker="o", markersize=5,
                label="1.2.1 corrected (with trend)")
        ax.plot(x, [float(r["coefficient_median"]) for r in b], color=ORANGE, linewidth=2, linestyle="--",
                marker="o", markersize=5, label="1.2.0 flawed (no trend)")
        ax.axhline(0, color=MUTED, linewidth=1)
        ax.set_xticks(list(x))
        ax.set_xticklabels([r["month"] for r in g], fontsize=8)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
        ax.tick_params(colors=MUTED, labelsize=9)
        ax.grid(axis="y", color=GRID)
        ax.set_axisbelow(True)
        ax.set_title(f"{EQ[eq]}: fuel coefficient at lag 1", loc="left", color=INK, fontsize=11)
    axes[0].set_ylabel("Elasticity (log points per log point)", color=MUTED, fontsize=9)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, frameon=False, fontsize=9, labelcolor=MUTED, loc="lower center", ncol=3)
    fig.tight_layout(rect=(0, 0.08, 1, 1))
    fig.savefig(V1 / "fuel_coefficient_path.png", dpi=160, metadata={"Software": "Matplotlib"})
    plt.close(fig)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    texts = {V0 / "README.md": build_v0(), V1 / "README.md": build_v1()}
    if a.check:
        for path, text in texts.items():
            if path.read_text() != text:
                raise SystemExit(f"{path} differs from saved results")
        print("READMEs match saved results")
    else:
        figure()
        for path, text in texts.items():
            path.write_text(text)
        print("Wrote both READMEs and fuel_coefficient_path.png")
