"""Write results/multibrand/README.md from the saved CSVs (no fitting).

python -m scripts.multibrand_report [--check]
"""
import argparse
import csv
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/multibrand"
POLICY = ("innovation_premium", "grant_2023_all", "grant_2023_private", "pre_cut_2022_12",
          "pre_business_end_2023_08", "tax_package_2025_07", "grant_2026")
PRICES = ("log_electricity", "log_new_cars")
EQS = ("log_market", "alr_Tesla", "alr_VW_Group", "alr_BMW_Group", "alr_Mercedes", "alr_Hyundai_Kia", "log_fuel")
EQ_LABEL = {"log_market": "BEV market", "alr_Tesla": "Tesla/Rest", "alr_VW_Group": "VW Group/Rest",
            "alr_BMW_Group": "BMW Group/Rest", "alr_Mercedes": "Mercedes/Rest",
            "alr_Hyundai_Kia": "Hyundai-Kia/Rest", "log_fuel": "Fuel price"}


def rows(name):
    with (OUT / name).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def cell(r, digits=2):
    m, lo, hi = (float(r[k]) for k in ("median", "lower95", "upper95"))
    mark = " **†**" if r["excludes_zero"] == "True" else ""
    return f"{m:+.{digits}f} [{lo:+.{digits}f}; {hi:+.{digits}f}]{mark}"


def pct(x):
    return f"{(math.exp(x) - 1) * 100:+.0f} %"


def build():
    coef = {(r["equation"], r["term"]): r for r in rows("coefficients.csv") if r["spec"] == "primary"}
    met = {(r["spec"], r["outcome"], r["period"], r["horizon"]): r for r in rows("metrics.csv")}
    hyp = rows("hypotheses.csv")
    irf = {(r["spec"], r["variable"], r["h"]): r for r in rows("irf_fuel_shock.csv")}
    man = json.loads((OUT / "manifest.json").read_text())
    pred = {(r["spec"], r["target"], r["horizon"], r["outcome"]): r for r in rows("predictions.csv")}
    L = []
    a = L.append
    a("# Multi-brand BVARX: results (protocol `multibrand-bvarx/1.0.0`)\n")
    a("Generated by `python -m scripts.multibrand_report` from the CSV files in this folder; "
      "no number below is typed by hand. Protocol: [docs/MULTIBRAND_BVAR_PROTOCOL.md]"
      "(../../docs/MULTIBRAND_BVAR_PROTOCOL.md), SHA-256 `" + man["protocol_sha256"][:16] + "…`, "
      f"{man['draws']:,} posterior draws, seed {man['seed']}.\n")
    a("**Model.** Bayesian VARX(1) with a Minnesota prior on 69 months (2021-01 – 2026-09). "
      "Endogenous: Euro-super 95 price, BEV market, and the log ratios of Tesla, VW Group, BMW Group, "
      "Mercedes and Hyundai-Kia to the rest of the BEV market. Exogenous: calendar, quarter-end, "
      "seven incentive indicators, HICP electricity and HICP new cars. All coefficients are "
      "**conditional associations**, not causal effects; † = 95 % posterior interval excludes zero.\n")

    a("## 1. Verdicts\n")
    a("| Hypothesis | Primary | λ = 0.1 | λ = 0.5 | No prices | Fuel calendar-day (2022-05+) |")
    a("|---|---|---|---|---|---|")
    order = ["H-F market", "H-F Tesla share", "H-P2026", "H-Tax", "Forecast gain Tesla vs M2",
             "Forecast gain BEV_market vs M2"]
    by = {(r["spec"], r["hypothesis"]): r for r in hyp}
    for h in order:
        cells = []
        for s in ("primary", "lambda_0.1", "lambda_0.5", "no_prices", "fuel_calendar_day"):
            r = by.get((s, h))
            cells.append(r["verdict"] + (f" ({r['median']})" if r and h.startswith("Forecast") else "") if r else "–")
        a(f"| {h} | " + " | ".join(cells) + " |")
    a("\nRules (frozen): *supported* / *weakened* when the 95 % interval lies entirely above / below "
      "zero (forecast: BVARX beats Task 04 M2 in all / none of 2025 h=1, 2025 h=3, 2026 h=1, 2026 h=3); "
      "otherwise *open*.\n")

    a("## 2. Incentive programmes (primary model)\n")
    a("Differences to the baseline January 2024 – June 2025 (no purchase grant, company-car cap 70k EUR). "
      "Market column in log points; the brand columns change the log ratio to Rest.\n")
    a("| Programme | " + " | ".join(EQ_LABEL[e] for e in EQS[:6]) + " |")
    a("|---|" + "---|" * 6)
    for t in POLICY:
        a(f"| `{t}` | " + " | ".join(cell(coef[(e, t)]) for e in EQS[:6]) + " |")
    a("\nFor reading the market column: " + "; ".join(
        f"`{t}` {float(coef[('log_market', t)]['median']):+.2f} ≈ {pct(float(coef[('log_market', t)]['median']))}"
        for t in POLICY) + ".")
    own = float(coef[("log_market", "lag1:log_market")]["median"])
    a(f"These are same-month coefficients. The market equation also carries its own lag "
      f"(posterior median {own:+.2f}), so a programme that stays in force accumulates further "
      f"over subsequent months; pulses (`pre_*`) are one-month pull-forward spikes.\n")
    a("## 3. Prices and quarter-end (primary model)\n")
    a("| Term | " + " | ".join(EQ_LABEL[e] for e in EQS) + " |")
    a("|---|" + "---|" * 7)
    for t in PRICES + ("quarter_end",):
        a(f"| `{t}` | " + " | ".join(cell(coef[(e, t)]) for e in EQS) + " |")
    a("\nPrice coefficients are elasticities with respect to the index level. Both HICP series trend "
      "over the window together with BEV adoption, so their signs partly absorb trends; they are "
      "controls, not demand elasticities.\n")

    a("## 4. Fuel price shock (fuel ordered first)\n")
    sd = man["specs"]["primary"]["fuel_shock_sd"]
    a(f"One posterior-median standard deviation of the fuel innovation is {sd * 100:.1f} % of the "
      "Euro-super 95 price. Cumulative response over months 0–11 (sum of log responses):\n")
    a("| Specification | BEV market | Tesla/Rest | VW Group/Rest | BMW Group/Rest | Mercedes/Rest | Hyundai-Kia/Rest |")
    a("|---|---|---|---|---|---|---|")
    for s in ("primary", "lambda_0.1", "lambda_0.5", "no_prices", "fuel_calendar_day"):
        a(f"| {s} | " + " | ".join(
            cell({**irf[(s, v, 'cum_0_11')], 'excludes_zero': str(float(irf[(s, v, 'cum_0_11')]['lower95']) > 0
                                                                  or float(irf[(s, v, 'cum_0_11')]['upper95']) < 0)})
            for v in EQS[:6]) + " |")
    a("\n![Impulse responses to a fuel price shock](irf_fuel_shock.png)\n")

    a("## 5. Forecasts against Task 04 (identical target months)\n")
    a("RMSE in registrations per month (lower is better). 2026 = January–September; October 2026 has "
      "no Task 04 comparator.\n")
    for outcome in ("Tesla", "BEV_market"):
        a(f"**{outcome.replace('_', ' ')}**\n")
        a("| Model | 2025 h=1 | 2025 h=3 | 2026 h=1 | 2026 h=3 | Oct 2026 h=1 | Oct 2026 h=3 |")
        a("|---|---|---|---|---|---|---|")
        for s in ("primary", "lambda_0.1", "lambda_0.5", "no_prices", "M2", "M0", "seasonal_naive"):
            vals = []
            for p, h in (("2025", "1"), ("2025", "3"), ("2026", "1"), ("2026", "3"), ("2026-10", "1"), ("2026-10", "3")):
                r = met.get((s, outcome, p, h))
                vals.append(f"{float(r['rmse']):,.0f}" if r else "–")
            a(f"| {s} | " + " | ".join(vals) + " |")
        a("")
    oct1, oct3 = pred[("primary", "2026-10", "1", "Tesla")], pred[("primary", "2026-10", "3", "Tesla")]
    a(f"October 2026, Tesla: actual {float(oct1['actual']):,.0f}; BVARX one month ahead "
      f"{float(oct1['prediction_median']):,.0f} [{float(oct1['lower95']):,.0f}; {float(oct1['upper95']):,.0f}], "
      f"three months ahead {float(oct3['prediction_median']):,.0f} "
      f"[{float(oct3['lower95']):,.0f}; {float(oct3['upper95']):,.0f}].\n")
    a("![Tesla one-month-ahead forecasts](tesla_forecasts_h1.png)\n")

    a("## 6. Limits\n")
    a("- 69 months, 7 equations, 21 regressors per equation: the prior matters (see λ sensitivities).\n"
      "- Incentives coincide with the 2022 energy shock, model launches and Tesla's 2025 share loss; "
      "the end of the Umweltbonus and the 70k company-car cap cannot be separated.\n"
      "- Chinese brands are partly hidden in KBA `SONSTIGE` and stay in Rest.\n"
      "- No brand-level prices exist; HICP new cars is a market-wide index.\n"
      "- Fuel is endogenous by request; only the fuel shock is identified (recursive ordering).\n"
      "- HICP after the forecast origin is held at its last value; incentives enter only once announced.\n")
    a("## Files\n")
    a("`coefficients.csv` (all terms incl. lags, all specifications), `irf_fuel_shock.csv`, "
      "`predictions.csv` (BVARX and comparators), `metrics.csv`, `hypotheses.csv`, `manifest.json` "
      "(input/code/output hashes, versions). Reproduce:\n")
    a("```sh\npython -m multibrand.study\npython -m scripts.multibrand_figures\npython -m scripts.multibrand_report\n```")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    text = build()
    if a.check:
        if (OUT / "README.md").read_text() != text:
            raise SystemExit("README differs from saved results")
        print("README matches saved results")
    else:
        (OUT / "README.md").write_text(text)
        print("Wrote results/multibrand/README.md")
