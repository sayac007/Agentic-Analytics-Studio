"""README and figure for results/multibrand_fuel_lags from saved CSVs (no fitting).

python -m scripts.multibrand_fuel_lags_report [--check]
"""
import argparse
import csv
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results/multibrand_fuel_lags"
INK, MUTED, GRID, SURFACE, BLUE, BAND = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb", "#2a78d6", "#86b6ef"


def rows(name):
    with (OUT / name).open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def ci(r, bonf=True):
    s = f"{float(r['median']):+.2f} [{float(r['lower95']):+.2f}; {float(r['upper95']):+.2f}]"
    if bonf:
        s += f" ({float(r['lower_bonf']):+.2f}; {float(r['upper_bonf']):+.2f})"
    return s


def build():
    coef = {(r["L"], r["equation"], r["term"]): r for r in rows("lag_coefficients.csv")}
    irf = {(r["L"], r["equation"]): r for r in rows("irf_cumulative.csv")}
    ml = rows("marginal_likelihood.csv")
    hyp = rows("hypotheses.csv")
    met = {(r["spec"], r["outcome"], r["period"], r["horizon"]): r for r in rows("metrics.csv")}
    man = json.loads((OUT / "manifest.json").read_text())
    L = []
    a = L.append
    a("# Fuel price at lags 1–4 (amendment `multibrand-bvarx/1.1.0-fuel-lags`)\n")
    a("Generated by `python -m scripts.multibrand_fuel_lags_report` from the CSVs in this folder. "
      "[Amendment](../../docs/MULTIBRAND_FUEL_LAGS_PROTOCOL.md) frozen before fitting (SHA-256 `"
      + man["protocol_sha256"][:16] + f"…`); {man['draws']:,} draws per variant, identical outcome months "
      f"{man['outcome_months']}. Variant L adds Euro-super 95 at lags 2…L to every equation of the "
      "[base model](../multibrand/README.md); L = 1 is the base model. Intervals: 95 % in brackets, "
      "Bonferroni 98.75 % in parentheses. Associations, not causal effects.\n")
    a("## 1. Direct fuel-lag coefficients (elasticities, log points per log point of fuel)\n")
    a("| L | BEV market: lag 1 | lag 2 | lag 3 | lag 4 | **sum of lags** |")
    a("|---|---|---|---|---|---|")
    for lag in ("1", "2", "3", "4"):
        cells = [ci(coef[(lag, "log_market", f"fuel_lag{j}")], False) if (lag, "log_market", f"fuel_lag{j}") in coef
                 else "–" for j in (1, 2, 3, 4)]
        a(f"| {lag} | " + " | ".join(cells) + f" | {ci(coef[(lag, 'log_market', 'fuel_lag_sum')])} |")
    a("")
    a("| L | Tesla/Rest: lag 1 | lag 2 | lag 3 | lag 4 | **sum of lags** |")
    a("|---|---|---|---|---|---|")
    for lag in ("1", "2", "3", "4"):
        cells = [ci(coef[(lag, "alr_Tesla", f"fuel_lag{j}")], False) if (lag, "alr_Tesla", f"fuel_lag{j}") in coef
                 else "–" for j in (1, 2, 3, 4)]
        a(f"| {lag} | " + " | ".join(cells) + f" | {ci(coef[(lag, 'alr_Tesla', 'fuel_lag_sum')])} |")
    m1 = coef[("1", "log_market", "fuel_lag1")]
    a(f"\nReading: in the base model a 10 % higher fuel price goes with a "
      f"{(math.exp(0.1 * float(m1['median'])) - 1) * 100:+.1f} % BEV market in the following month "
      f"(95 % interval {(math.exp(0.1 * float(m1['lower95'])) - 1) * 100:+.1f} % to "
      f"{(math.exp(0.1 * float(m1['upper95'])) - 1) * 100:+.1f} %).\n")
    a("## 2. Cumulative response to a one-SD fuel shock (months 0–11)\n")
    a("| L | BEV market | Tesla/Rest | VW Group/Rest | BMW Group/Rest | Mercedes/Rest | Hyundai-Kia/Rest |")
    a("|---|---|---|---|---|---|---|")
    for lag in ("1", "2", "3", "4"):
        a(f"| {lag} | " + " | ".join(ci(irf[(lag, e)]) for e in
                                     ("log_market", "alr_Tesla", "alr_VW_Group", "alr_BMW_Group", "alr_Mercedes",
                                      "alr_Hyundai_Kia")) + " |")
    a("\n![Cumulative market response by lag depth](cumulative_market_response.png)\n")
    a("## 3. Verdicts\n")
    a("| L | H-F market | H-F Tesla share |")
    a("|---|---|---|")
    by = {(h["L"], h["hypothesis"]): h["verdict"] for h in hyp}
    for lag in ("1", "2", "3", "4"):
        a(f"| {lag} | {by[(lag, 'H-F market')]} | {by[(lag, 'H-F Tesla share')]} |")
    a(f"| all | {by[('all', 'H-F market across lags')]} | {by[('all', 'H-F Tesla share across lags')]} |\n")
    a("## 4. Lag depth: log marginal likelihood\n")
    best = max(float(r["log_marginal_likelihood"]) for r in ml)
    a("| L | Regressors per equation | log marginal likelihood | difference to best |")
    a("|---|---|---|---|")
    for r in ml:
        v = float(r["log_marginal_likelihood"])
        a(f"| {r['L']} | {r['regressors_per_equation']} | {v:.2f} | {v - best:+.2f} |")
    a("\nDifferences below about 1 log unit (Bayes factor < e ≈ 2.7) are conventionally not worth more "
      "than a bare mention; they also depend on the prior.\n")
    a("## 5. Forecast RMSE (registrations per month)\n")
    for outcome in ("Tesla", "BEV_market"):
        a(f"**{outcome.replace('_', ' ')}**\n")
        a("| Model | 2025 h=1 | 2025 h=3 | 2026 h=1 | 2026 h=3 | Oct 2026 h=1 | Oct 2026 h=3 |")
        a("|---|---|---|---|---|---|---|")
        for s in ("L1", "L2", "L3", "L4", "M2"):
            vals = []
            for p, h in (("2025", "1"), ("2025", "3"), ("2026", "1"), ("2026", "3"), ("2026-10", "1"), ("2026-10", "3")):
                r = met.get((s, outcome, p, h))
                vals.append(f"{float(r['rmse']):,.0f}" if r else "–")
            a(f"| {s} | " + " | ".join(vals) + " |")
        a("")
    a("## Files\n")
    a("`lag_coefficients.csv`, `irf_cumulative.csv`, `marginal_likelihood.csv`, `predictions.csv`, "
      "`metrics.csv`, `hypotheses.csv`, `manifest.json`. Reproduce:\n")
    a("```sh\npython -m multibrand.fuel_lags\npython -m scripts.multibrand_fuel_lags_report\n```")
    return "\n".join(L) + "\n"


def figure():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    irf = {r["L"]: r for r in rows("irf_cumulative.csv") if r["equation"] == "log_market"}
    fig, ax = plt.subplots(figsize=(7, 3.9), facecolor=SURFACE)
    ax.set_facecolor(SURFACE)
    for i, lag in enumerate(("1", "2", "3", "4")):
        r = irf[lag]
        ax.plot([float(r["lower_bonf"]), float(r["upper_bonf"])], [i, i], color=BAND, linewidth=2,
                label="98.75 % (Bonferroni)" if i == 0 else None)
        ax.plot([float(r["lower95"]), float(r["upper95"])], [i, i], color=BLUE, linewidth=4,
                solid_capstyle="round", label="95 %" if i == 0 else None)
        ax.plot(float(r["median"]), i, "o", color=INK, markersize=7, label="Median" if i == 0 else None)
    ax.axvline(0, color=MUTED, linewidth=1)
    ax.set_yticks(range(4))
    ax.set_yticklabels([f"Lags 1–{l}" if l != "1" else "Lag 1 (base)" for l in ("1", "2", "3", "4")])
    ax.invert_yaxis()
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(colors=MUTED, labelsize=9)
    ax.grid(axis="x", color=GRID)
    ax.set_axisbelow(True)
    ax.set_xlabel("Cumulative log response of the BEV market, months 0–11, to a one-SD fuel shock",
                  color=MUTED, fontsize=9)
    ax.set_title("Fuel price shock and BEV market by lag depth", loc="left", color=INK, fontsize=11)
    ax.legend(frameon=False, fontsize=8, labelcolor=MUTED, loc="upper center",
              bbox_to_anchor=(0.5, -0.22), ncol=3)
    fig.tight_layout()
    fig.savefig(OUT / "cumulative_market_response.png", dpi=160, metadata={"Software": "Matplotlib"})
    plt.close(fig)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    text = build()
    if a.check:
        if (OUT / "README.md").read_text() != text:
            raise SystemExit("README differs from saved results")
        print("README matches saved results")
    else:
        figure()
        (OUT / "README.md").write_text(text)
        print("Wrote README.md and cumulative_market_response.png")
